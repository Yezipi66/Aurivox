// ---------------------------------------------------------------------------
//  训练管线的身份 —— 这一条声明是**全仓库唯一**一处
// ---------------------------------------------------------------------------
//
// ⭐⭐⭐ 刀 A2（2026-08-31）新建。
//
// ## 这个文件为什么存在
//
// A2 的题目是「模型位名字改从名片读（slotDir / slotFromMeta 的第二参）」。
// 取证之后，那 15 处写死的 `"gpt-sovits"` 不是同一件事，是**两件**：
//
// | 类 | 在问什么 | 正确答案 |
// |---|---|---|
// | **合成路径** | 「这次请求点名的那台引擎，它的模型位叫什么、选中的那份用哪个键发出去」 | ⭐ **从名片读**（`profile.weight_slots[].name` / `.param`）。已改，见 `routes/synthesis.js` 整音色那一段 |
// | **训练管线** | 「**我**训出来的东西该放进谁的目录」 | ⭐ **管线自己知道**。它不是"默认引擎"，是这条流水线的身份 |
//
// ⛔ 第二类**不许**改成"从名片读"。那会是一句更漂亮的谎：
//   平台今天只有一条训练管线，它从头到尾是 GPT-SoVITS 的形状 ——
//   S1/S2 两阶段、`.ckpt` + `.pth` 两种权重、`process_ckpt` 的版本头。
//   把这条管线的产物写进「用户当前选中的那台引擎」的目录，
//   等于把 GSV 的权重塞进 IndexTTS2 的格子里，然后它会在合成时才炸。
//
// ## 那为什么还要这个文件？
//
// 因为 15 处**散落的字符串字面量**和 1 处**具名声明**是两种东西：
//   - 散落的字面量：每一处都在**各自主张**「默认引擎是 gpt-sovits」，
//     读代码的人分不清哪一处是管线身份、哪一处是漏掉的默认值。
//   - 具名声明：只有这一处主张，其余全是**引用**。
//     第二条训练管线进来的那天，要改的是这一个文件，不是满仓库 grep。
//
// ⭐ 这条路 `lib/assetScanner.js:480` 已经先走了一步
//   （`_LEGACY_GSV_ENGINE_ID`，Owner 2026-08-30 裁决「标签留着，但现在不搬」）。
//   本文件是把那个做法**推广到全部训练相关调用点**。
//
// ## 禁令
//
// ⛔ 不许把 `TRAINING_ENGINE_ID` 当成「默认引擎」用在**合成**路径上。
//    合成路径永远问名片（`callEngine.id` / `callEngine.weight_slots`）。
//    判据很简单：如果你正在回答「用户想用哪台」，⛔ 这个常量是错的答案；
//    如果你正在回答「我刚训出来的东西是谁的」，✅ 才是它。
// ⛔ 不许在 `lib/` / `server.js` 的任何别处再写 `"gpt-sovits"` 这个字面量。
//
// ## 预言（可证伪）
//
// 第二条训练管线（比如给 IndexTTS2 做微调）进来时，会有人想把这个常量改成
// 一个参数、或者改成"从当前选中的引擎读"。那一天真正要做的是：
// **训练管线本身变成一个可注册的东西**（每条管线带着自己的
// `engineId` + 阶段表 + 权重后缀），而不是给这一个常量加一个开关。
// ⭐ 判据：如果改完之后 `TRAINING_STAGES` 这类东西还写死在平台里，
//   那么这个常量动态化了也没用 —— 产物形状还是 GSV 的。

/**
 * 平台今天**唯一**一条训练管线所属的引擎 id。
 *
 * ⚠ 它同时也是磁盘目录名：`assets/<角色>/models/<这个值>/<权重位>/`。
 * ⚠ 与 `engines/gpt-sovits/manifest.json` 的 `id` 必须一致 ——
 *   不一致的后果是训练产物落在一个没有引擎认领的目录里，界面上"有模型"、
 *   合成时"找不到"。`pipelineIdentity.node.test.js` 守着这一条。
 */
const TRAINING_ENGINE_ID = 'gpt-sovits';

/**
 * 这条管线产出的两个权重位，及各自的文件后缀。
 *
 * ⚠ 位名必须出现在 `engines/gpt-sovits/manifest.json` 的 `weights` 里，
 *   否则训出来的东西扫得到、归不了位（`slotResolve.js` 只认名片声明的位）。
 */
const TRAINING_SLOTS = Object.freeze({
  /** S1 / GPT 阶段的产物 */
  gpt: Object.freeze({ name: 'gpt', ext: '.ckpt' }),
  /** S2 / SoVITS 阶段的产物 */
  sovits: Object.freeze({ name: 'sovits', ext: '.pth' }),
});

module.exports = { TRAINING_ENGINE_ID, TRAINING_SLOTS };
